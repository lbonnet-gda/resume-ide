<?php

namespace App\Tests\Controller;

use App\DataFixtures\AppFixtures;
use App\Entity\Profile;
use Doctrine\Common\DataFixtures\Purger\ORMPurger;
use Doctrine\ORM\EntityManagerInterface;
use Symfony\Bundle\FrameworkBundle\KernelBrowser;
use Symfony\Bundle\FrameworkBundle\Test\WebTestCase;
use Symfony\Component\HttpClient\MockHttpClient;
use Symfony\Component\HttpClient\Response\MockResponse;
use Symfony\Component\Security\Core\User\UserProviderInterface;

final class ResumePdfControllerTest extends WebTestCase
{
    private const string PDF = '%PDF-1.7 generated by the mock';

    private KernelBrowser $client;
    private EntityManagerInterface $entityManager;

    /** @var list<array{url: string, body: string}> */
    private array $gotenbergRequests = [];

    protected function setUp(): void
    {
        $this->client = self::createClient([], ['HTTPS' => 'on']);
        // The mocked transport is set on this container: a reboot between requests would drop it.
        $this->client->disableReboot();
        $this->entityManager = self::getContainer()->get(EntityManagerInterface::class);

        new ORMPurger($this->entityManager)->purge();
        new AppFixtures()->load($this->entityManager);

        $transport = self::getContainer()->get('http_client.mock_transport');
        self::assertInstanceOf(MockHttpClient::class, $transport);
        $transport->setResponseFactory(function (string $method, string $url, array $options): MockResponse {
            if ($method === 'GET' && str_ends_with($url, '/version')) {
                return new MockResponse('8.25.0');
            }

            $this->gotenbergRequests[] = ['url' => $url, 'body' => self::readBody($options['body'])];

            return new MockResponse(self::PDF, ['response_headers' => ['Content-Type' => 'application/pdf']]);
        });
    }

    public function testPublicPdfIsGeneratedFromTheResumeWithoutThePhoneNumber(): void
    {
        $this->client->request('GET', '/resume.pdf');

        self::assertResponseIsSuccessful();
        self::assertResponseHeaderSame('Content-Type', 'application/pdf');
        self::assertResponseHeaderSame('Content-Disposition', 'attachment; filename=CV-Jane-Doe.pdf');
        self::assertResponseHeaderSame('X-Robots-Tag', 'noindex');
        self::assertSame(self::PDF, $this->client->getResponse()->getContent());

        self::assertCount(1, $this->gotenbergRequests);
        self::assertSame('http://gotenberg:3000/forms/chromium/convert/html', $this->gotenbergRequests[0]['url']);
        $body = $this->gotenbergRequests[0]['body'];
        self::assertStringContainsString("name=\"preferCssPageSize\"\r\n\r\ntrue", $body);
        self::assertStringContainsString("name=\"generateTaggedPdf\"\r\n\r\ntrue", $body);
        self::assertStringContainsString('filename="index.html"', $body);
        self::assertStringContainsString('filename="inter-latin-400-normal.woff2"', $body);
        self::assertStringContainsString('filename="inter-latin-600-normal.woff2"', $body);
        self::assertStringContainsString('<title>Jane Doe - CV</title>', $body);
        self::assertStringContainsString('Lead développeuse Symfony', $body);
        self::assertStringContainsString('septembre 2021</time> –', $body);
        self::assertStringNotContainsString($this->profile()->getPhone(), $body);
        self::assertStringNotContainsString('tel:', $body);
    }

    public function testAdminPdfIsGeneratedSeparatelyWithThePhoneNumber(): void
    {
        $provider = self::getContainer()->get('security.user.provider.concrete.admin');
        self::assertInstanceOf(UserProviderInterface::class, $provider);
        $this->client->loginUser($provider->loadUserByIdentifier('admin'), 'admin');
        $this->client->request('GET', '/resume.pdf');

        $this->client->request('GET', '/admin/resume.pdf');

        self::assertResponseIsSuccessful();
        self::assertResponseHeaderSame('Content-Disposition', 'attachment; filename=CV-Jane-Doe-with-phone.pdf');
        self::assertSame(self::PDF, $this->client->getResponse()->getContent());
        self::assertCount(2, $this->gotenbergRequests);
        self::assertStringContainsString('<a href="tel:+33639980000">+33 6 39 98 00 00</a>', $this->gotenbergRequests[1]['body']);
    }

    public function testAnonymousVisitorCannotDownloadThePdfWithThePhoneNumber(): void
    {
        $this->client->request('GET', '/admin/resume.pdf');

        self::assertResponseRedirects('/admin/login');
        self::assertSame([], $this->gotenbergRequests);
    }

    public function testPdfIsCachedUntilTheResumeChanges(): void
    {
        $this->client->request('GET', '/resume.pdf');
        $this->client->request('GET', '/resume.pdf');

        self::assertCount(1, $this->gotenbergRequests);

        $this->profile()->setTitle('Architecte logicielle');
        $this->entityManager->flush();
        $this->client->request('GET', '/resume.pdf');

        self::assertResponseIsSuccessful();
        self::assertCount(2, $this->gotenbergRequests);
        self::assertStringContainsString('Architecte logicielle', $this->gotenbergRequests[1]['body']);
    }

    public function testEmptyResumeHasNoPdf(): void
    {
        new ORMPurger($this->entityManager)->purge();

        $this->client->request('GET', '/resume.pdf');

        self::assertResponseStatusCodeSame(503);
        self::assertSelectorTextContains('h1', 'This résumé is empty');
        self::assertSame([], $this->gotenbergRequests);
    }

    private function profile(): Profile
    {
        $profile = $this->entityManager->getRepository(Profile::class)->findOneBy([]);
        self::assertNotNull($profile);

        return $profile;
    }

    private static function readBody(mixed $body): string
    {
        if (!is_callable($body)) {
            return is_string($body) ? $body : '';
        }

        $content = '';

        while (is_string($chunk = $body(16_384)) && $chunk !== '') {
            $content .= $chunk;
        }

        return $content;
    }
}
